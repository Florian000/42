#include <unistd.h>
#include "ft_bsq.h"

int	main(int ac, char **av)
{
	int	i;

	if (ac == 1)
	{
		ft_map("stdin", 0);
		return (0);
	}
	i = 1;
	while (i < ac)
	{
		ft_map(av[i++], 1);
		if (i != ac)
			write(1, "\n", 1);
	}
	return (0);
}

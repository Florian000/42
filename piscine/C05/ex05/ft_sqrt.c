int	ft_sqrt(int nb)
{
	int	i;

	i = 1;
	if (nb == 1)
		return (1);
	while ((nb / i) >= i)
	{
		i++;
		if ((nb / i == i) && (nb % i) == 0)
			return (i);
	}
	return (0);
}

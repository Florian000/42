#include "doop.h"

int	ft_add(long int a, long int b)
{
	return (a + b);
}

int	ft_sub(long int a, long int b)
{
	return (a - b);
}

int	ft_div(long int a, long int b)
{
	return (a / b);
}

int	ft_mul(long int a, long int b)
{
	return (a * b);
}

int	ft_mod(long int a, long int b)
{
	return (a % b);
}
